#!/usr/bin/env python3
"""Regenerate src/api/ca_roots.h from the system trust store.

The node verifies the API's TLS certificate against these roots. They cover
the CAs Cloudflare issues edge certificates from (Let's Encrypt, Google Trust
Services, SSL.com). Re-run after a CA change:

    python3 tools/update_ca_roots.py [/etc/ssl/certs]

Check the current chain with:
    openssl s_client -connect sensor.devgoblin.fr:443 -showcerts </dev/null
"""

import os
import sys

ROOTS = [
    "ISRG_Root_X1.pem",
    "ISRG_Root_X2.pem",
    "GTS_Root_R1.pem",
    "GTS_Root_R4.pem",
    "SSL.com_Root_Certification_Authority_RSA.pem",
    "SSL.com_Root_Certification_Authority_ECC.pem",
]

store = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs"
out_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "src", "api", "ca_roots.h")

lines = [
    "#pragma once",
    "",
    "// Generated by tools/update_ca_roots.py from the system trust store. Do not edit.",
    "// Root CAs trusted for the HTTPS API: " + ", ".join(r[:-4] for r in ROOTS) + ".",
    "",
    "static const char API_CA_ROOTS[] =",
]
for name in ROOTS:
    path = os.path.join(store, name)
    with open(path, encoding="ascii") as handle:
        pem = handle.read().strip()
    if "BEGIN CERTIFICATE" not in pem:
        raise SystemExit(f"{path}: not a PEM certificate")
    lines.append(f"    // {name[:-4]}")
    for row in pem.splitlines():
        lines.append(f'    "{row}\\n"')
lines[-1] += ";"
os.makedirs(os.path.dirname(out_path), exist_ok=True)
with open(out_path, "w", encoding="ascii") as handle:
    handle.write("\n".join(lines) + "\n")
print(f"wrote {out_path} ({len(ROOTS)} roots)")
