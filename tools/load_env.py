# PlatformIO pre-build script: turns the gitignored .env at the project root
# into a generated header, so credentials never live in a tracked file.
#
#   WIFI_SSID=my-lab
#   WIFI_PASSWORD="pass with spaces"
#
# The header is written to $BUILD_DIR/generated/env_secrets.h (never tracked)
# and picked up by src/utils/secrets.h. A header rather than -D flags because
# values then never go through a shell: quotes, backslashes and '$' in a
# password survive untouched.
#
# Only the keys in STRING_KEYS / INT_KEYS are forwarded; anything else in .env
# is ignored. Keys not set in .env keep their defaults from secrets.h.

import os

Import("env")  # noqa: F821  (injected by PlatformIO)

STRING_KEYS = (
    "WIFI_SSID",
    "WIFI_PASSWORD",
    "WIFI_EAP_IDENTITY",
    "WIFI_EAP_USERNAME",
    "WIFI_EAP_PASSWORD",
    "MQTT_BROKER",
    "MQTT_USERNAME",
    "MQTT_PASSWORD",
    "GEOHASH_DEFAULT",
    "FIRMWARE_URL",
    "FIRMWARE_SIG_URL",
)
INT_KEYS = ("MQTT_PORT",)

# Keys whose value is a path (relative to the project root) to a file whose
# contents become the define: WIFI_EAP_CA_FILE=certs/ca.pem -> WIFI_EAP_CA_PEM.
FILE_KEYS = {"WIFI_EAP_CA_FILE": "WIFI_EAP_CA_PEM"}


def parse_env(path):
    values = {}
    with open(path, encoding="utf-8") as handle:
        for lineno, raw in enumerate(handle, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("export "):
                line = line[len("export "):].lstrip()
            if "=" not in line:
                print(f"[.env] line {lineno}: no '=', ignored")
                continue
            key, value = line.split("=", 1)
            key, value = key.strip(), value.strip()
            if value[:1] in ("\"", "'"):
                # Quoted: everything up to the matching quote, literally.
                end = value.find(value[0], 1)
                if end == -1:
                    raise SystemExit(f"[.env] line {lineno}: unterminated quote")
                value = value[1:end]
            else:
                # Unquoted: " #" starts a comment. Quote values containing " #".
                cut = value.find(" #")
                if cut != -1:
                    value = value[:cut].rstrip()
                elif value.startswith("#"):
                    value = ""
            values[key] = value
    return values


def c_string(value):
    out = []
    for ch in value:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "?":
            out.append("\\?")  # no accidental trigraphs
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            # UTF-8 bytes as octal escapes: never merge with a following digit.
            out.extend("\\%03o" % b for b in ch.encode("utf-8"))
    return '"' + "".join(out) + '"'


def render(values, project_dir):
    lines = [
        "// Generated by tools/load_env.py from .env. Do not edit, do not commit.",
        "#pragma once",
    ]
    for key in STRING_KEYS:
        if key in values:
            lines.append(f"#define {key} {c_string(values[key])}")
    for key in INT_KEYS:
        if key in values:
            if not values[key].isdigit():
                raise SystemExit(f"[.env] {key} must be an integer, got {values[key]!r}")
            lines.append(f"#define {key} {int(values[key])}")
    for key, define in FILE_KEYS.items():
        if values.get(key):
            path = os.path.join(project_dir, values[key])
            if not os.path.isfile(path):
                raise SystemExit(f"[.env] {key}: file not found: {values[key]}")
            with open(path, encoding="utf-8") as handle:
                lines.append(f"#define {define} {c_string(handle.read())}")
    return "\n".join(lines) + "\n"


def write_if_changed(path, content):
    # Rewriting an identical file would force a rebuild of everything.
    try:
        with open(path, encoding="utf-8") as handle:
            if handle.read() == content:
                return
    except FileNotFoundError:
        pass
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)


project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
env_path = os.path.join(project_dir, ".env")
header_path = os.path.join(gen_dir, "env_secrets.h")

os.makedirs(gen_dir, exist_ok=True)
env.Append(CPPPATH=[gen_dir])  # noqa: F821

if os.path.isfile(env_path):
    values = parse_env(env_path)
    write_if_changed(header_path, render(values, project_dir))
    loaded = [k for k in STRING_KEYS + INT_KEYS + tuple(FILE_KEYS) if values.get(k)]
    # Never print values: build logs end up in CI and terminal scrollback.
    print("[.env] loaded: " + (", ".join(loaded) or "nothing"))
else:
    write_if_changed(header_path, "#pragma once\n// No .env: defaults from secrets.h.\n")
    print("[.env] not found; using defaults from src/utils/secrets.h "
          "(cp .env.example .env)")
